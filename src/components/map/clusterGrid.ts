/**
 * 클러스터 격자 규칙 — 지도 WebView에 **이 문자열 그대로** 주입되고,
 * 같은 문자열을 유닛 테스트가 평가해 검증한다(구현이 둘로 갈라지지 않도록).
 *
 * 지켜야 할 성질:
 *   "확대(레벨 감소)하면 묶음은 쪼개지기만 하고, 절대 새로 합쳐지지 않는다."
 *
 * 왜 이게 중요한가:
 *   예전 구현은 `Math.round(lat / g)`를 썼다. round의 버킷 경계는 g의 반정수 배
 *   (k+0.5)g에 생기는데, 이 경계는 2g 격자의 경계와 겹치지 않는다.
 *   그래서 축소 상태에서 경계를 사이에 두고 갈라져 있던 두 점이,
 *   확대하면 같은 버킷으로 들어가 **없던 클러스터가 생기는** 일이 실제로 일어났다.
 *   (동탄 일대 좌표 2만 개 검사 시 반례 50,584건)
 *
 *   floor를 쓰고 모든 격자를 GRID_BASE·2^k 꼴로 두면 좁은 격자의 버킷이
 *   넓은 격자 버킷에 정확히 포함된다 → 같은 좁은 버킷이면 반드시 같은 넓은 버킷.
 *   따라서 확대는 쪼개기만 한다. (반례 0건)
 *
 * ⚠️ 이 문자열은 브라우저에서 그대로 실행된다. 바깥 스코프를 참조하지 말 것.
 */
export const CLUSTER_GRID_JS = `
      // 격자 기준 폭(위도 0.00004° ≈ 4.4m).
      // 카카오는 레벨당 축척이 2배씩 벌어지므로(레벨5 ≈ 4.8m/px, 레벨7 ≈ 19m/px)
      // 격자를 2^level에 비례시키면 화면상 묶임 간격이 약 30px로 고정된다.
      var GRID_BASE = 0.00004;
      // 이 레벨보다 확대된 구간(레벨이 더 작음)에서는 좌표가 사실상 동일한 것만 묶는다.
      var CLUSTER_MIN_LEVEL = 5;

      function activeGridFor(level) {
        return level >= CLUSTER_MIN_LEVEL ? GRID_BASE * Math.pow(2, level) : GRID_BASE;
      }

      // floor 필수 — round를 쓰면 격자가 중첩되지 않아 확대 시 새 클러스터가 생긴다(위 주석 참고)
      function groupKeyOf(lat, lng, g) {
        return Math.floor(lat / g) + ':' + Math.floor(lng / g);
      }
`;
