/**
 * 사진 미리보기 규칙 — 장소 상세와 마이 화면이 같아야 한다.
 *
 * 왜 한 곳에 두나:
 *   두 화면이 각자 상수를 갖고 있었고, 실제로 어긋났다.
 *   마이는 3장이었는데 장소 상세는 서버가 준 12장을 전부 그리고 있었다.
 *   같은 "사진 + 전체보기" 패턴이 한 앱에서 3과 12로 갈려 있었다.
 *
 * 3인 이유: 그리드가 3열이라 딱 한 줄로 떨어진다. 그 아래 내용에 닿기까지의
 * 스크롤을 늘리지 않으면서 "여기 사진이 있다"는 것은 보여준다.
 *
 * ⚠️ 서버 응답까지 이 값으로 자르지 않는다. 전체보기가 재요청 없이 열려야 한다.
 *    자르는 것은 화면뿐이다.
 */
export const PHOTO_PREVIEW = 3;

/**
 * 그리드 열 수. 지금은 PHOTO_PREVIEW와 같은 값이지만 **뜻이 다르다** —
 * 이건 칸 너비를 정하고, 저건 몇 장을 보여줄지를 정한다.
 * 하나로 합쳐 쓰면 "미리보기를 6장으로 늘리자"가 칸 너비까지 반토막 낸다.
 * 미리보기를 한 줄로 유지하는 한 두 값은 같다.
 */
export const PHOTO_COLUMNS = 3;

