/**
 * email — 이메일 주소 형식 검사
 *
 * 로그인·가입·비밀번호 찾기가 같은 기준을 쓴다. 예전엔 화면마다 `[^\s@]+@[^\s@]+\.[^\s@]+`를
 * 따로 들고 있었는데, 이 식은 한글 자모("ㅁ@ㅁ.ㅁ")도 통과시켜 서버에 보내 본 뒤에야
 * 실패를 알렸다. 여기서는 영문·숫자·허용 기호로만 된 주소를 받는다.
 *  - 로컬파트: 영문·숫자·`._%+-`
 *  - 도메인: 영문·숫자·하이픈 라벨(앞뒤 하이픈 불가)이 점으로 이어지고, 최상위 도메인은 영문 2자 이상
 * 국제화 도메인(IDN)은 받지 않는다 — 가입 실데이터에 없고, Supabase 발송도 ASCII 기준이다.
 */
const EMAIL_RE =
  /^[A-Za-z0-9._%+-]+@(?:[A-Za-z0-9](?:[A-Za-z0-9-]*[A-Za-z0-9])?\.)+[A-Za-z]{2,}$/;

export function isValidEmail(value: string): boolean {
  return EMAIL_RE.test(value.trim());
}
