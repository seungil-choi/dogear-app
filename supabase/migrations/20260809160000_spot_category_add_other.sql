-- spot_category에 'other' 추가
--
-- 왜: 장소 제안에서 맞는 유형이 없으면 사용자가 아무거나 고르게 된다.
--     틀린 유형으로 들어온 장소는 아이콘·핀·필터가 전부 어긋나는데,
--     어드민은 그게 틀렸다는 사실 자체를 알 방법이 없다.
--     '기타'는 "모르겠다"를 정직하게 담는 자리다 — 어드민이 재분류하면 된다.
--     (사용자 제안 장소는 status='hidden'으로 들어와 어차피 검토를 거친다)
--
-- 공공데이터에는 이 값이 없다. 사용자 제안 전용이다.
alter type public.spot_category add value if not exists 'other';
