-- 사용자 제안 장소를 '즉시 노출 + 검토 중' 상태로 두기 위한 새 상태.
--
-- 왜 hidden을 재사용하지 않는가:
--   hidden은 **운영자가 내린 것**(위반·신고)이다. 여기에 사용자 제안을 겹쳐 두면
--   "hidden을 공개로 연다"는 정책이 되어 위반 콘텐츠까지 함께 열린다.
--
-- 왜 active로 넣지 않는가:
--   active로 넣으면 추천·검색·지도가 전부 자동으로 집어간다. 어느 한 곳을 빠뜨리면
--   '검토 중' 표시 없이 노출된다. 새 값을 만들면 반대가 된다 — 읽는 쪽이 명시적으로
--   pending을 포함해야 보인다. **빠뜨렸을 때 과다노출이 아니라 미노출로 실패한다.**
alter type public.spot_status add value if not exists 'pending';
